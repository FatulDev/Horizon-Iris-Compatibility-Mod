#!/usr/bin/env python3
"""Builds the Iris Features native mod bundle from the reference implementation
(~/iris-mod/ref, Horizon's branch `iris-features`) and the pinned pristine source."""
import json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rsx
from rsx import take, cut, strip_tests, outer_docs, sub1

ROOT = os.path.dirname(HERE)
REF = os.path.join(ROOT, 'ref')
PRISTINE = os.path.expanduser('~/hz-pristine')
OUT = os.path.join(ROOT, 'out', 'iris-features')

MOD_ID = 'iris-features'
VERSION = '0.1.16'
HORIZON = 'fca2169de9c014be8b6606ac1f3dba0bcda3731a'
MIXINS = '5140cdf81915c25f10a7745eb532e1c09f275068'

def ref(path):
    return open(os.path.join(REF, path)).read()

def pristine(path):
    return open(os.path.join(PRISTINE, path)).read()

def own(name):
    return open(os.path.join(ROOT, 'src', name)).read()

files = {}
toml = [f'''[mod]
id = "{MOD_ID}"
version = "{VERSION}"
priority = 100

[compatibility]
horizon_revision = "{HORIZON}"
''']

HEADER = '// Iris Features (native mod for Horizon). Generated by tools/build.py; edit the sources.\n'

def module(id, file, name, source_text, visibility=None):
    fname = f'{id}.rs'
    files[fname] = HEADER + source_text
    vis = f'\nvisibility = "{visibility}"' if visibility else ''
    toml.append(f'''[[module]]
id = "{id}"
file = "{file}"
name = "{name}"
source = "{fname}"{vis}
''')

def binding(name, ty, value):
    return '{ name = "%s", ty = "%s", value = "%s" }' % (name, ty, value)

def hook(id, target, helper_text, bindings, kind='HEAD', cancellable=True, extra=''):
    fname = f'hook-{id}.rs'
    files[fname] = helper_text
    canc = '\ncancellable = true' if cancellable and kind == 'HEAD' else ''
    toml.append(f'''[[injection]]
id = "{id}"
target = "{target}"
kind = "{kind}"{canc}
helper = "{fname}"
bindings = [{", ".join(bindings)}]{extra}
''')

def fn_body(src):
    """`fn ...(...) -> T { BODY }` → BODY (with its braces)."""
    i = src.index('{', re.search(r'\)\s*(->[^{]*)?\{', src).start())
    return src[i:]

def deindent(src, n=4):
    out = []
    for l in src.split('\n'):
        out.append(l[n:] if l.startswith(' ' * n) else l.lstrip(' ') if not l.strip() else l)
    return '\n'.join(out)

# ---------------------------------------------------------------------------------------------
# horizon-shaders
# ---------------------------------------------------------------------------------------------
SH = 'crates/horizon-shaders/src/'

# The crate's public `iris` module: the format's declarations, the options `.properties` see,
# the macros, and the doors the other crates use.
iris = strip_tests(ref(SH + 'iris.rs')).rstrip() + '\n\n' + own('shaders_iris_extra.rs')
# The GL extension Iris names for images (every GPU Iris runs on has it): Eclipse's floodfill
# lighting voxelises and reads its light volume only with it.
iris = sub1(iris, '    m.define("IRIS_FEATURE_CUSTOM_TEXTURE_NAME", "");\n',
            '    m.define("IRIS_FEATURE_CUSTOM_TEXTURE_NAME", "");\n    m.define("MC_GL_ARB_shader_image_load_store", "");\n')
# Value options as the shader options menu finds them (`iris_options`): a list anywhere in the
# comment, `const` options too, at the player's values.
iris, _ = cut(iris, r'^fn source_texts\(')
iris, _ = cut(iris, r'^pub fn value_options\(')
iris = iris.replace('const SOURCES: [&str; 8] = ["vsh", "fsh", "gsh", "csh", "tcs", "tes", "glsl", "inc"];\n\n', '')
iris = sub1(iris, 'use std::collections::{BTreeMap, BTreeSet};', 'use std::collections::BTreeMap;')
iris = iris.rstrip() + '''

/// The value of each value option as the pack is read now (`iris_options::value_options`).
pub fn value_options(pack: &Pack) -> BTreeMap<String, String> {
    crate::iris_options::value_options(pack)
}
'''
module('shaders-iris', SH + 'lib.rs', 'iris', iris, 'pub')

# Shader options: the pack's options, screens and profiles for the menu (game side), and the
# player's values written into the sources as they are read.
module('shaders-options', SH + 'lib.rs', 'iris_options', own('shaders_options.rs'), 'pub')
hook('pack-read-text', 'horizon_shaders::pack::Pack::read_text', '''\
fn iris_read_text(pack: &Pack, path: &str) -> ::core::ops::ControlFlow<Option<String>> {
    ::core::ops::ControlFlow::Break(crate::iris_options::read_text(pack, path))
}
''', [binding('pack', '&Pack', 'self'), binding('path', '&str', 'path')])

# `#if` with decimals.
cond = strip_tests(outer_docs(ref(SH + 'condition.rs')))
for h in [r'^pub\(crate\) fn split_directive\(', r'^struct Branch \{', r'^#\[derive\(Default\)\]\npub\(crate\) struct Conditionals',
          r'^impl Conditionals \{', r'^fn test\(']:
    cond, _ = cut(cond, h)
cond = re.sub(r'^(//.*\n)+\n', '', cond, count=1)  # the file's opening comment
cond = cond.replace('pub fn eval_condition(', 'pub(crate) fn eval_condition(')
module('shaders-condition', SH + 'condition.rs', 'iris_condition',
       '// `#if` arithmetic that takes decimals, as Iris\'s preprocessor does.\n' + cond)
hook('eval-condition', 'horizon_shaders::condition::eval_condition', '''\
fn iris_eval_condition(expr: &str, macros: &crate::Macros) -> ::core::ops::ControlFlow<Result<i64, String>> {
    ::core::ops::ControlFlow::Break(iris_condition::eval_condition(expr, macros))
}
''', [binding('expr', '&str', 'expr'), binding('macros', '&crate::Macros', 'macros')])

# `smooth()` state forgotten after the renderer's trial evaluation.
module('shaders-custom', SH + 'custom.rs', 'iris_custom', '''\
// Forgets what `smooth` has seen, so the next evaluation starts each one at its value.
pub(crate) fn forget_smoothing(custom: &mut super::Custom) {
    custom.smooth.clear();
}
''')

# `.properties` with the pack's options in custom uniform expressions.
props = take(ref(SH + 'properties.rs'), r'^    pub fn parse\(')
props = deindent(props)
props = props.replace('pub fn parse(', 'pub(crate) fn parse(').replace('-> Self {', '-> Properties {')
props = sub1(props, 'Self::default()', 'Properties::default()')
module('shaders-properties', SH + 'properties.rs', 'iris_properties',
       '// `Properties::parse`, with custom uniform expressions reading the pack\'s options.\nuse super::*;\n\n' + props)

# Post: compute programs, the declared resources, pass-through geometry stages.
post_ref = ref(SH + 'post.rs')
parts = []
for h in [r'^pub struct ComputePass \{', r'^#\[derive\(Default\)\]\npub struct IrisPost \{',
          r'^const COMPUTE_STAGES', r'^fn load_computes\(', r'^fn passes_through\(',
          r'^pub fn load_post\(', r'^fn load_shadow\(']:
    parts.append(take(post_ref, h))
load = deindent(take(post_ref, r'^    fn load\(\n        &mut self,'))
load = sub1(load, 'fn load(\n    &mut self,', 'fn load(\n    this: &mut Loader<\'_>,')
load = re.sub(r'\bself\.', 'this.', load)
parts.append(load)
post = '\n'.join(parts)
post = post.replace('pub fn load_post(', 'pub(crate) fn load_post(')
post = sub1(post, '        iris: IrisPost::default(),\n', '')
post = sub1(post, '    load_computes(&mut loader);\n', '    crate::iris::set_pending(load_computes(&mut loader));\n')
# load_computes builds and returns the dimension's IrisPost.
post = sub1(post, 'fn load_computes(loader: &mut Loader<\'_>) {\n    let mut computes = Vec::new();',
            'fn load_computes(loader: &mut Loader<\'_>) -> IrisPost {\n    let mut iris = IrisPost::default();\n    let mut computes = Vec::new();')
post = post.replace('loader.post.iris.', 'iris.')
post = sub1(post, 'match crate::translate_compute(&code)', 'match crate::iris::translate_compute(&code)')
post = post.rstrip()
# Close load_computes with its result.
post = sub1(post, '''                .push(format!("custom texture {path}: no such file in the pack")),
        }
    }
}''', '''                .push(format!("custom texture {path}: no such file in the pack")),
        }
    }
    iris
}''')
ls_start = post.index('fn load_shadow(')
ls_end = post.index('\n}\n', ls_start)
post = (re.sub(r'\bloader\.load\(', 'load(&mut loader, ', post[:ls_start])
        + re.sub(r'\bloader\.load\(', 'load(loader, ', post[ls_start:ls_end])
        + post[ls_end:])
post = post.replace('pub program: crate::ComputeProgram,', 'pub program: crate::iris::ComputeProgram,')
# `gbuffers_particles_translucent` (Iris): the translucent particles' own program, and the
# `particles.ordering` of each kind (`mixed`: opaque before deferred, translucent after).
post = sub1(post, '''    pub texture_files: std::collections::BTreeMap<String, Vec<u8>>,
}''', '''    pub texture_files: std::collections::BTreeMap<String, Vec<u8>>,
    /// `gbuffers_particles_translucent`, when the pack has it: the particles on the translucent
    /// layer draw with it, the others with `gbuffers_particles`.
    pub particles_translucent: Option<PostProgram>,
    /// With `particles_translucent`: whether the opaque particles draw after deferred.
    pub particles_opaque_late: bool,
    /// `rainDepth`: rain and snow write depth (Iris: only when the pack asks).
    pub rain_depth: bool,
}''')
post = sub1(post, '    let particles = translucent(&PARTICLES, 0.1, &mut gbuffers_dyn);\n',
            '    let particles = translucent(&PARTICLES, 0.1, &mut gbuffers_dyn);\n'
            '    let particles_translucent = translucent(&["gbuffers_particles_translucent"], 0.1, &mut gbuffers_dyn);\n')
post = sub1(post, '    crate::iris::set_pending(load_computes(&mut loader));\n', '''    let mut iris = load_computes(&mut loader);
    iris.particles_translucent = particles_translucent.filter(|_| loader.post.particles.is_some());
    iris.particles_opaque_late = match properties.get("particles.ordering").map(str::trim) {
        Some("after") => true,
        Some(_) => false,
        None => loader.post.particles_late,
    };
    iris.rain_depth = properties.get("rain.depth").is_some_and(|v| v.trim() == "true");
    crate::iris::set_pending(iris);
''')
module('shaders-post', SH + 'post.rs', 'iris_post',
       '// `load_post` with compute programs and the pack\'s resources, and geometry stages that only\n'
       '// pass triangles through.\nuse super::*;\n\n' + post + '\n')
hook('load-post', 'horizon_shaders::post::load_post', '''\
fn iris_load_post(
    pack: &Pack,
    folder: &str,
    properties: &Properties,
    macros: &Macros,
    inputs: &GameInputs,
) -> ::core::ops::ControlFlow<Post> {
    ::core::ops::ControlFlow::Break(iris_post::load_post(pack, folder, properties, macros, inputs))
}
''', [binding('pack', '&Pack', 'pack'), binding('folder', '&str', 'folder'),
      binding('properties', '&Properties', 'properties'), binding('macros', '&Macros', 'macros'),
      binding('inputs', '&GameInputs', 'inputs')])

# The translator.
tr_ref = ref(SH + 'translate/mod.rs')
tparts = ['use super::*;\nuse std::collections::BTreeMap;\nuse std::fmt::Write;\n\nuse naga::ShaderStage;\n'
          'use naga::front::glsl::{Frontend, Options};\nuse naga::valid::{Capabilities, ValidationFlags, Validator};\n\n'
          'use crate::Preprocessed;\n\nuse scan::Stage;\n']
for h in [r'^#\[derive\(Clone, Debug, PartialEq\)\]\npub struct ImageUse', r'^fn image_uses\(', r'^fn image_declarations\(',
          r'^fn translate\(', r'^#\[derive\(Clone, Copy, Debug, PartialEq\)\]\npub enum WorkGroups',
          r'^#\[derive\(Debug\)\]\npub struct ComputeProgram|^pub struct ComputeProgram', r'^fn constant_arguments\(',
          r'^pub fn translate_compute\(', r'^fn compile\(', r'^fn component_arguments\(']:
    tparts.append(take(tr_ref, h))
tr = '\n'.join(tparts)
tr = tr.replace('fn translate(', 'pub(crate) fn translate(', 1)
tr = re.sub(r'\n(\s*)images,\n\s*buffers,\n', '\n', tr)
def submod(name):
    s = strip_tests(outer_docs(ref(SH + f'translate/{name}.rs'))).rstrip()
    return f'mod {name} {{\n{rsx.indent(s)}\n}}\n'
tr += '\n' + submod('scan') + '\n' + submod('rewrite')
tr += own('shaders_atomic_stores.rs')
tr = sub1(tr, '    let mut module = module;\n', '    let mut module = module;\n    if stage.kind == ShaderStage::Vertex {\n        atomic_vertex_stores(&mut module);\n    }\n')
module('shaders-translate', SH + 'translate/mod.rs', 'iris_translate',
       '// The translator with Iris\'s storage buffers, images and compute programs, and the GLSL\n'
       '// packs written for Iris rely on.\n' + tr)
hook('translate', 'horizon_shaders::translate::translate', '''\
fn iris_translate(
    vertex: &Preprocessed,
    fragment: &Preprocessed,
    target: Target,
    gbuffers: Option<&GbuffersInputs>,
    shadow: bool,
) -> ::core::ops::ControlFlow<Result<Program, Vec<Error>>> {
    ::core::ops::ControlFlow::Break(iris_translate::translate(vertex, fragment, target, gbuffers, shadow))
}
''', [binding('vertex', '&Preprocessed', 'vertex'), binding('fragment', '&Preprocessed', 'fragment'),
      binding('target', 'Target', 'target'), binding('gbuffers', 'Option<&GbuffersInputs>', 'gbuffers'),
      binding('shadow', 'bool', 'shadow')])

if os.environ.get('ONLY') == 'shaders':
    pass
else:
    exec(open(os.path.join(HERE, 'build_render.py')).read())

# ---------------------------------------------------------------------------------------------
shutil.rmtree(OUT, ignore_errors=True)
os.makedirs(OUT)
for name, text in files.items():
    open(os.path.join(OUT, name), 'w').write(text)
open(os.path.join(OUT, 'horizon-mixin.toml'), 'w').write('\n'.join(toml))
print(f'{len(files)} files in {OUT}')
