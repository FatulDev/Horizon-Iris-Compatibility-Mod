"""Builds the Iris Features native mod bundle for Horizon main from the development branch
(`ref/`: the files of Horizon's branch `iris-dev`, Horizon with the mod's changes made in place) and the pinned
pristine source (~/hz-pristine). Each changed function is copied from the branch into a module
of the mod beside the original, and a cancellable HEAD hook sends calls to the copy."""
import os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rsx
from rsx import take, strip_tests, sub1

ROOT = os.path.dirname(HERE)
DEV = os.path.join(ROOT, 'ref')
PRISTINE = os.path.expanduser('~/hz-pristine')
OUT = os.path.join(ROOT, 'out', 'iris_features')

MOD_ID = 'iris_features'
VERSION = '0.1.31'
HORIZON = '10b16c4b94d6ebdf3234545f53243c6466dfa32c'
MIXINS = '4342a0bfbe71d4d14185528d64e496d6022f16a1'

SH = 'crates/horizon-shaders/src/'
RE = 'crates/horizon-client-render/src/'

def dev(path):
    return open(os.path.join(DEV, path)).read()

def pristine(path):
    return open(os.path.join(PRISTINE, path)).read()

files = {}
toml = [f'''[mod]
id = "{MOD_ID}"
version = "{VERSION}"
priority = 100

[compatibility]
horizon_revision = "{HORIZON}"
''']

HEADER = '// Iris Features (native mod for Horizon). Generated by tools/build.py; edit the sources.\n'

def module(id, file, name, text, visibility=None):
    fname = f'{id}.rs'
    files[fname] = HEADER + text
    vis = f'\nvisibility = "{visibility}"' if visibility else ''
    toml.append(f'''[[module]]
id = "{id}"
file = "{file}"
name = "{name}"
source = "{fname}"{vis}
''')

def binding(name, ty, value):
    return '{ name = "%s", ty = "%s", value = "%s" }' % (name, ty, value.replace('"', '\\"'))

def hook(id, target, helper, bindings, kind='HEAD', cancellable=True):
    fname = f'hook-{id}.rs'
    files[fname] = helper
    canc = '\ncancellable = true' if cancellable and kind == 'HEAD' else ''
    toml.append(f'''[[injection]]
id = "{id}"
target = "{target}"
kind = "{kind}"{canc}
helper = "{fname}"
bindings = [{", ".join(bindings)}]
''')

def deindent(src, n=4):
    return '\n'.join(l[n:] if l.startswith(' ' * n) else l for l in src.split('\n'))

def split_top(s, sep=','):
    out, depth, cur = [], 0, ''
    prev = ''
    for c in s:
        if c in '<([{':
            depth += 1
        elif c in ')]}' or (c == '>' and prev != '-'):
            depth -= 1
        prev = c
        if c == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]

def signature(fn_text):
    """(name, params [(name, type)], self kind or None, return type) of `fn` text."""
    m = re.search(r'fn\s+(\w+)\s*(<[^>]*>)?\s*\(', fn_text)
    name = m.group(1)
    i = m.end()
    depth, j = 1, i
    while depth:
        if fn_text[j] == '(':
            depth += 1
        elif fn_text[j] == ')':
            depth -= 1
        j += 1
    params_text = fn_text[i:j - 1]
    rest = fn_text[j:fn_text.index('{', j)]
    ret = rest.strip()[2:].strip() if rest.strip().startswith('->') else '()'
    params, selfk = [], None
    for p in split_top(params_text):
        p = re.sub(r'^mut\s+', '', p)
        if re.fullmatch(r'&\s*(\'\w+\s+)?(mut\s+)?self|mut\s+self|self', p):
            selfk = p.replace(' ', '')
            continue
        m2 = re.match(r'^(\w+)\s*:(?!:)\s*(.*)$', p, re.S)
        params.append((m2.group(1), m2.group(2).strip()))
    return name, params, selfk, ret

def replace(id, path, header_re, target, owner=None, nth=0, self_ty=None, edit=None):
    """Copies the item `header_re` of `path` from the development branch into module
    `iris_<id>` beside it, and hooks `target` to call the copy. `owner`: the type a method
    belongs to (`self` becomes `this`, `Self` the type)."""
    src = take(dev(path), header_re, nth)
    if edit:
        src = edit(src)
    name, params, selfk, ret = signature(src)
    body = deindent(src) if src.startswith('    ') else src
    body = re.sub(r'\bpub(\([^)]*\))?\s+fn\b', 'fn', body, count=1)
    body = body.replace(f'fn {name}', f'pub(super) fn iris_{name}', 1)
    args = [n for n, _ in params]
    binds = []
    if selfk is not None:
        ty = self_ty or owner
        this_ty = {'&self': f'&{ty}', '&mutself': f'&mut {ty}', 'self': ty, 'mutself': ty}[selfk]
        body = re.sub(r'\(\s*(&\s*(\'\w+\s+)?(mut\s+)?)?(mut\s+)?self\s*(,\s*)?', lambda m: '(this: ' + this_ty + (', ' if m.group(5) else ''), body, count=1)
        body = re.sub(r'\bself\b', 'this', body)
        args = ['this'] + args
        binds.append(binding('this', this_ty, {'&self': '&*self', '&mutself': '&mut *self'}.get(selfk, 'self')))
    if owner:
        body = re.sub(r'\bSelf\b', owner.split('<')[0], body)
    for n, t in params:
        binds.append(binding(n, t, n))
    plist = ', '.join(f'{n}: {t}' for n, t in ([('this', binds[0].split('ty = "')[1].split('"')[0])] if selfk else []) + params)
    module(f'm-{id}', path, f'iris_{id.replace("-", "_")}', 'use super::*;\n\n' + body + '\n')
    helper = f'''fn iris_{id.replace("-", "_")}_hook({plist}) -> ::core::ops::ControlFlow<{ret}> {{
    ::core::ops::ControlFlow::Break(iris_{id.replace("-", "_")}::iris_{name}({", ".join(args)}))
}}
'''
    hook(id, target, helper, binds)

# --- horizon-shaders ----------------------------------------------------------------------------

# The crate's door for the mod: image atomics, the images declared 1D.
module('shaders-iris', SH + 'lib.rs', 'iris', re.sub(r'^//!', '//', dev(SH + 'iris.rs'), flags=re.M), 'pub')

# The translator: the module's functions and its submodules, copied whole (their private types
# change), with GLSL Iris's drivers accept, naga's frontend vendored with fixes, and passes over
# the parsed module. The public entry points go to the copies.
tr = strip_tests(dev(SH + 'translate/mod.rs'))
# Public types stay Horizon's: the copy uses them through `super::*`.
for kw in ['struct', 'enum', 'type', 'const', 'static']:
    while True:
        m = re.search(r'^(#\[[^\n]*\]\n|///[^\n]*\n)*pub(\([^)]*\))? %s \w+' % kw, tr, re.M)
        if not m:
            break
        tr = tr[:m.start()] + tr[rsx.item_span(tr, re.escape(m.group(0).split('\n')[-1]))[1]:].lstrip('\n')
for m in list(re.finditer(r'^impl(<[^>]*>)? (\w+)', tr, re.M))[::-1]:
    s, e = rsx.item_span(tr, re.escape(m.group(0)) + r'\b', 0)
    # Methods of Horizon's types stay Horizon's (the copy calls them).
    tr = tr[:s] + tr[e:].lstrip('\n')
for line in ['use iris_glsl::frontend::{Frontend, Options};\n', 'use iris_passes::*;\n']:
    tr = tr.replace(line, '', 1)
tr = re.sub(r'^(pub )?mod \w+;\n', '', tr, flags=re.M)
tr = re.sub(r'^pub use [^\n]*\n', '', tr, flags=re.M)
tr = tr.replace('pub fn translate_', 'pub(crate) fn translate_')
def submod(name, src):
    return f'pub(super) mod {name} {{\n{rsx.indent(strip_tests(src).rstrip())}\n}}\n'
glsl = dev(SH + 'translate/iris_glsl.rs').replace('crate::translate::iris_glsl::', 'crate::translate::iris_translate::iris_glsl::')
passes = dev(SH + 'translate/iris_passes.rs')
passes = re.sub(r'\nstatic IMAGE_ATOMICS.*', '\npub(super) fn image_atomics_on() -> bool {\n    crate::iris::image_atomics()\n}\n', passes, flags=re.S)
parts = ['use super::*;\nuse iris_glsl::frontend::{Frontend, Options};\nuse iris_passes::*;\n', tr]
for name in ['scan', 'rewrite', 'ordering', 'atomic_vectors', 'geometry']:
    text = dev(SH + f'translate/{name}.rs')
    if name == 'geometry':
        text = text.replace(take(text, r'^(#\[[^\n]*\]\n)*pub struct GeometryInputs'), '', 1)
        text = text.replace('use super::{Error, GbuffersInputs, Program, Target};', 'use super::{Error, GeometryInputs, Program, Target};')
    parts.append(submod(name, text))
parts.append('pub(crate) mod iris_glsl {\n' + glsl + '\n}\n')
parts.append('#[allow(dead_code)]\nmod iris_passes {\n' + passes.replace('#![allow(dead_code)]\n', '') + '\n}\n')
module('shaders-translate', SH + 'translate/mod.rs', 'iris_translate', re.sub(r'^(\s*)//!', r'\1//', '\n'.join(parts), flags=re.M))
for name in ['translate_composite', 'translate_gbuffers', 'translate_shadow', 'translate_compute', 'translate_geometry']:
    geo = name == 'translate_geometry'
    src = take(dev(SH + ('translate/geometry.rs' if geo else 'translate/mod.rs')), r'^pub fn %s\(' % name)
    _, params, _, ret = signature(src)
    plist = ', '.join(f'{n}: {t}' for n, t in params)
    target = 'horizon_shaders::translate::geometry::translate_geometry' if geo else f'horizon_shaders::translate::{name}'
    path = 'super::iris_translate::geometry::translate_geometry' if geo else f'iris_translate::{name}'
    hook(name.replace('_', '-'), target, f'''fn iris_{name}({plist}) -> ::core::ops::ControlFlow<{ret}> {{
    ::core::ops::ControlFlow::Break({path}({", ".join(n for n, _ in params)}))
}}
''', [binding(n, t, n) for n, t in params])

# Iris's macros: its version and the extensions it defines whatever the GPU.
defs = re.findall(r'^        m\.define\("(IRIS_VERSION|MC_GL_ARB_shader_image_load_store|MC_NORMAL_MAP|MC_SPECULAR_MAP|MC_GL_ARB_texture_gather|MC_GL_EXT_gpu_shader4)", "([^"]*)"\);', dev(SH + 'macros.rs'), re.M)
IRIS_MACROS = ''.join(f'    macros.define("{n}", "{v}");\n' for n, v in defs)

replace('preprocess-file', SH + 'preprocess.rs', r'^    fn file\(', "horizon_shaders::preprocess::Run<'_>::file", owner="Run<'_>")
replace('load-post', SH + 'post.rs', r'^pub fn load_post\(', 'horizon_shaders::post::load_post',
        edit=lambda t: t.replace('loader.load(', 'super::iris_loader_load::iris_load(&mut loader, ').replace('CustomImage::parse(', 'super::iris_custom_image_parse::iris_parse(').replace('expand_custom(', 'super::iris_post_extra::expand_custom('))
ll = deindent(take(dev(SH + 'post.rs'), r'^    fn load\(\n\s*&mut self')).replace('passes_through(', 'super::iris_post_extra::passes_through(')
ll = re.sub(r'fn load\(\s*&mut self,', "pub(super) fn iris_load(this: &mut Loader<'_>,", ll, count=1)
ll = re.sub(r'\bself\b', 'this', ll)
module('m-loader-load', SH + 'post.rs', 'iris_loader_load', 'use super::*;\n\n' + ll)
ci = deindent(take(dev(SH + 'post.rs'), r'^    fn parse\(name: &str, value: &str\)')).replace('fn parse(', 'pub(super) fn iris_parse(', 1)
module('m-custom-image-parse', SH + 'post.rs', 'iris_custom_image_parse', 'use super::*;\n\n' + re.sub(r'\bSelf\b', 'CustomImage', ci))
module('shaders-post-extra', SH + 'post.rs', 'iris_post_extra', 'use super::*;\n\n' + take(dev(SH + 'post.rs'), r'^fn passes_through\(').replace('fn passes_through', 'pub(super) fn passes_through') + '\n' + take(dev(SH + 'post.rs'), r'^fn expand_custom\(').replace('fn expand_custom', 'pub(super) fn expand_custom'))

if os.environ.get('ONLY') != 'shaders':
    exec(open(os.path.join(HERE, 'build_render.py')).read())

shutil.rmtree(OUT, ignore_errors=True)
